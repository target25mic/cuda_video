from IPython.display import display, Javascript, Image as IPImage
from google.colab.output import eval_js
from base64 import b64decode
import numpy as np
import cv2
import subprocess
import ipywidgets as widgets
import io, time

def run_cuda_pipeline(gray_frame):
    h, w = gray_frame.shape

    gray_frame.astype(np.float32).tofile('input.bin')
    result = subprocess.run(['./pipeline_live', str(w), str(h)],
                            capture_output=True, text=True)
    if result.returncode != 0:
        print('CUDA error:', result.stderr)
        return gray_frame
    out = np.fromfile('output.bin', dtype=np.float32).reshape(h, w)
    mn, mx = out.min(), out.max()
    if mx > mn:
        out = (out - mn) / (mx - mn) * 255.0
    return out.astype(np.uint8)

def decode_frame(data_url):
    """Returns (color BGR frame, grayscale frame)"""
    _, encoded = data_url.split(',', 1)
    img_array  = np.frombuffer(b64decode(encoded), dtype=np.uint8)
    frame_bgr  = cv2.imdecode(img_array, cv2.IMREAD_COLOR)
    frame_gray = cv2.cvtColor(frame_bgr, cv2.COLOR_BGR2GRAY)
    return frame_bgr, frame_gray


COLORMAP = cv2.COLORMAP_VIRIDIS

def colorize_edges(edge_gray):
    return cv2.applyColorMap(edge_gray, COLORMAP)

def show_side_by_side(original_bgr, edge_color):
    left, right = original_bgr.copy(), edge_color.copy()
    cv2.putText(left,  'Original (color)',   (10,30), cv2.FONT_HERSHEY_SIMPLEX, 0.9, (255,255,255), 2, cv2.LINE_AA)
    cv2.putText(right, 'CUDA Edges (color)', (10,30), cv2.FONT_HERSHEY_SIMPLEX, 0.9, (255,255,255), 2, cv2.LINE_AA)
    _, buf = cv2.imencode('.jpg', np.hstack([left, right]))
    display(IPImage(data=buf.tobytes()))

