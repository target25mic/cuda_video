from IPython.display import clear_output

NUM_FRAMES  = 30    # number of frames to capture
FRAME_DELAY = 0.1   # seconds between frames (~10 fps)

CAPTURE_JS = """
async function grabFrame() {
    const stream = await navigator.mediaDevices.getUserMedia({video: {width:640, height:480}});
    const video  = document.createElement('video');
    video.srcObject = stream;
    await new Promise(r => { video.onloadedmetadata = r; });
    video.play();
    await new Promise(r => setTimeout(r, 300));
    const canvas = document.createElement('canvas');
    canvas.width  = video.videoWidth;
    canvas.height = video.videoHeight;
    canvas.getContext('2d').drawImage(video, 0, 0);
    stream.getTracks().forEach(t => t.stop());
    return canvas.toDataURL('image/jpeg', 0.85);
}
grabFrame()
"""

out_widget  = widgets.Output()
display(out_widget)
frame_times = []

for i in range(NUM_FRAMES):
    t0 = time.time()

    data_url              = eval_js(CAPTURE_JS)
    frame_bgr, gray       = decode_frame(data_url)
    edge_gray             = run_cuda_pipeline(gray)
    edge_color            = colorize_edges(edge_gray)

    with out_widget:
        clear_output(wait=True)
        show_side_by_side(frame_bgr, edge_color)       # 5. display
        elapsed = time.time() - t0
        frame_times.append(elapsed)
        print(f'Frame {i+1}/{NUM_FRAMES}  |  CUDA: {elapsed*1000:.0f} ms  |  Avg FPS: {1/np.mean(frame_times):.1f}')

    time.sleep(max(0, FRAME_DELAY - elapsed))

print(f'\nDone! Avg pipeline time: {np.mean(frame_times)*1000:.1f} ms/frame')



